GODAN = {  # 連用形の末尾 → て形
    "い": "って", "り": "って", "ち": "って",
    "み": "んで", "び": "んで", "に": "んで",
    "き": "いて", "ぎ": "いで", "し": "して",
}
ICHIDAN_I = ("見", "借り", "降り", "浴び", "生き", "起き", "用い", "足り", "信じ", "感じ", "閉じ", "試み")

MASHOU = re.compile(r"([一-龥ぁ-んァ-ヶー々]{0,3}?)([ぁ-ん一-龥])ましょう")


def te_form(prefix: str, last: str) -> str:
    stem = prefix + last
    for ic in ICHIDAN_I:
        if stem.endswith(ic):
            return stem + "て"
    if last == "行" or stem.endswith("行き"):
        return stem[:-1] + "って" if stem.endswith("き") else stem + "って"
    if last in GODAN:
        return prefix + GODAN[last]
    # え段（一段動詞）・漢字1字（出る・見る 等）
    return stem + "て"


def repl_mashou(m: re.Match) -> str:
    prefix, last = m.group(1), m.group(2)
    stem = prefix + last
    for k, v in HONORIFIC.items():
        if stem.endswith(k):
            return stem[: -len(k)] + v + "ください"
    return te_form(prefix, last) + "ください"


REGEX_RULES = [
    # 「〜しましょう」→「〜してください」
    (MASHOU, repl_mashou),
    # メタ説明の体言止め（〜を解説。／〜を比較。／〜を紹介。）
    (re.compile(r"(を|も|まで|に|く|で)解説。"), r"\1解説します。"),
    (re.compile(r"(を|で|く)比較。"), r"\1比較します。"),
    (re.compile(r"(も|を)紹介。"), r"\1紹介します。"),
    (re.compile(r"まで網羅。"), "まで掲載しています。"),
    (re.compile(r"網羅。"), "掲載しています。"),
    # 「〜可能。」で終わる文
    (re.compile(r"可能。"), "可能です。"),
]

FILES = (
    glob.glob(f"{ROOT}/app/**/*.tsx", recursive=True)
    + glob.glob(f"{ROOT}/components/*.tsx")
    + [f"{ROOT}/data/articles-metadata.json", f"{ROOT}/data/dealers.ts"]
    + [f for f in glob.glob(f"{ROOT}/scripts/*.py") if not f.endswith("normalize-copy-202610.py")]
)

# 置換しない文字列（英語・コード・固有名詞の一部）
PROTECT = [
    "ヒカカク！", "ヤフオク！",
    "一番町",  # 仙台の地名
]


ESCAPED_RUN = re.compile(r"(?:\\u[0-9a-fA-F]{4})+(?:[^\"\\\n]{0,30}(?:\\u[0-9a-fA-F]{4})+)*")


def _normalize_escaped(text: str) -> tuple[str, int]:
    """JSON-LD（FAQPage 等）の \\uXXXX で書かれた日本語にも同じ規則を当てる。"""
    total = 0

    def rep(m):
        nonlocal total
        raw = m.group(0)
        dec = re.sub(r"\\u([0-9a-fA-F]{4})", lambda x: chr(int(x.group(1), 16)), raw)
        out, n = _normalize_plain(dec)
        if not n:
            return raw
        total += n
        return "".join(c if ord(c) < 128 else "\\u%04x" % ord(c) for c in out)

    return ESCAPED_RUN.sub(rep, text), total


def normalize(text: str) -> tuple[str, int]:
    text, n1 = _normalize_escaped(text)
    text, n2 = _normalize_plain(text)
    return text, n1 + n2


def _normalize_plain(text: str) -> tuple[str, int]:
    n = 0
    # 保護
    keys = {}
    for i, p in enumerate(PROTECT):
        k = f"{i}"
        keys[k] = p
        text = text.replace(p, k)
    for old, new in PHRASES:
        if old == new:
            continue
        c = text.count(old)
        if c:
            text = text.replace(old, new)
            n += c
    for rx, rep in REGEX_RULES:
        text, c = rx.subn(rep, text)
        n += c
    for k, p in keys.items():
        text = text.replace(k, p)
    return text, n


def main():
    dry = "--dry" in sys.argv
    total = 0
    changed = 0
    for f in sorted(set(FILES)):
        try:
            src = open(f, encoding="utf-8").read()
        except FileNotFoundError:
            continue
        out, n = normalize(src)
        if out != src:
            changed += 1
            total += n
            if not dry:
                open(f, "w", encoding="utf-8").write(out)
    print(f"{'(dry) ' if dry else ''}files changed: {changed} / replacements: {total}")


if __name__ == "__main__":
    main()
