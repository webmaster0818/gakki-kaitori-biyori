# ---------------------------------------------------------------- 〜しましょう → 〜してください
HONORIFIC = {
    "確認し": "ご確認",
    "相談し": "ご相談",
    "利用し": "ご利用",
    "活用し": "ご活用",
    "依頼し": "ご依頼",
    "検討し": "ご検討",
    "用意し": "ご用意",
}

GODAN = {  # 連用形の末尾 → て形
    "い": "って", "り": "って", "ち": "って",
    "み": "んで", "び": "んで", "に": "んで",
    "き": "いて", "ぎ": "いで", "し": "して",
}
ICHIDAN_I = ("見", "借り", "降り", "浴び", "生き", "起き", "用い", "足り", "信じ", "感じ", "閉じ", "試み")

MASHOU = re.compile(r"([一-龥ぁ-んァ-ヶー々]{0,3}?)([ぁ-ん一-龥])ましょう")


def te_form(prefix: str, last: str) -> str:
    stem = prefix + last
    for ic in ICHIDAN_I:
        if stem.endswith(ic):
            return stem + "て"
    if last == "行" or stem.endswith("行き"):
        return stem[:-1] + "って" if stem.endswith("き") else stem + "って"
    if last in GODAN:
        return prefix + GODAN[last]
    # え段（一段動詞）・漢字1字（出る・見る 等）
    return stem + "て"


def repl_mashou(m: re.Match) -> str:
    prefix, last = m.group(1), m.group(2)
    stem = prefix + last
    for k, v in HONORIFIC.items():
        if stem.endswith(k):
            return stem[: -len(k)] + v + "ください"
    return te_form(prefix, last) + "ください"


REGEX_RULES = [
    # 「〜しましょう」→「〜してください」
    (MASHOU, repl_mashou),
    # メタ説明の体言止め（〜を解説。／〜を比較。／〜を紹介。）
    (re.compile(r"(を|も|まで|に|く|で)解説。"), r"\1解説します。"),
    (re.compile(r"(を|で|く)比較。"), r"\1比較します。"),
    (re.compile(r"(も|を)紹介。"), r"\1紹介します。"),
    (re.compile(r"まで網羅。"), "まで掲載しています。"),
    (re.compile(r"網羅。"), "掲載しています。"),
    # 「〜可能。」で終わる文
    (re.compile(r"可能。"), "可能です。"),
    (re.compile(r"(?<![ぁ-ん])できる。"), "できます。"),
]

