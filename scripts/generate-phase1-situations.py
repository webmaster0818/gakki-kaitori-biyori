def md_to_html(text: str) -> str:
    """Convert **bold** to <strong>bold</strong>."""
    return re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)


def render_section(section: tuple) -> str:
    """Render a section's content from list of (type, body) tuples."""
    sec_id, sec_title, blocks = section
    parts = [f'        <h2 id="{sec_id}">{sec_title}</h2>']
    for block_type, body in blocks:
        if block_type == "text":
            parts.append(f"        <p>{md_to_html(body)}</p>")
        elif block_type == "h3":
            parts.append(f"        <h3>{body}</h3>")
        elif block_type == "ul":
            items = "".join(f"<li>{md_to_html(item)}</li>" for item in body)
            parts.append(f"        <ul>{items}</ul>")
        elif block_type == "ol":
            items = "".join(f"<li>{md_to_html(item)}</li>" for item in body)
            parts.append(f"        <ol>{items}</ol>")
        elif block_type == "table":
            rows = body
            header = "".join(f"<th>{h}</th>" for h in rows[0])
            body_rows = "".join(
                "<tr>" + "".join(f"<td>{md_to_html(c)}</td>" for c in row) + "</tr>"
                for row in rows[1:]
            )
            parts.append(
                f'        <div className="table-wrapper"><table><thead><tr>{header}</tr></thead><tbody>{body_rows}</tbody></table></div>'
            )
        elif block_type == "faq":
            for q, a in body:
                parts.append(
                    f'        <details className="border border-warm-border rounded-lg p-4 mb-3">'
                    f'<summary className="font-bold cursor-pointer flex justify-between items-center">{q}'
                    f'<svg className="faq-arrow w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24">'
                    f'<path strokeLinecap="round" strokeLinejoin="round" strokeWidth={{2}} d="M19 9l-7 7-7-7" /></svg>'
                    f'</summary><p className="mt-3 text-sm">{md_to_html(a)}</p></details>'
                )
    return "\n".join(parts)


def render_toc(sections: list) -> str:
    items = []
    for sec_id, title, _ in sections:
        items.append(f'            <li><a href="#{sec_id}" className="hover:underline">{title}</a></li>')
    return "\n".join(items)


def render_faq_schema(article: dict) -> list:
    """Extract FAQ items from sections for FAQPage schema."""
    faqs = []
    for sec in article["sections"]:
        for block_type, body in sec[2]:
            if block_type == "faq":
                for q, a in body:
                    faqs.append({
                        "@type": "Question",
                        "name": q,
                        "acceptedAnswer": {"@type": "Answer", "text": a.replace("**", "")},
                    })
    return faqs


