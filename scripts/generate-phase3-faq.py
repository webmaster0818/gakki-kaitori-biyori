def render_sections(secs: list) -> str:
    parts = []
    for sec in secs:
        if len(sec) != 3:
            continue
        sec_type, title, content = sec
        if sec_type == "h2":
            parts.append(f"        <h2>{title}</h2>")
        elif sec_type == "table":
            if title:
                parts.append(f"        <h3>{title}</h3>")
            if content:
                header = "".join(f"<th>{h}</th>" for h in content[0])
                body = "".join(
                    "<tr>" + "".join(f"<td>{md_to_html(c)}</td>" for c in row) + "</tr>"
                    for row in content[1:]
                )
                parts.append(f'        <div className="table-wrapper"><table><thead><tr>{header}</tr></thead><tbody>{body}</tbody></table></div>')
        elif sec_type == "ul":
            items = "".join(f"<li>{md_to_html(item)}</li>" for item in content)
            if title:
                parts.append(f"        <h3>{title}</h3>")
            parts.append(f"        <ul>{items}</ul>")
        elif sec_type == "ol":
            items = "".join(f"<li>{md_to_html(item)}</li>" for item in content)
            if title:
                parts.append(f"        <h3>{title}</h3>")
            parts.append(f"        <ol>{items}</ol>")
        elif sec_type == "text":
            parts.append(f"        <p>{md_to_html(title)}</p>")
    return "\n".join(parts)


